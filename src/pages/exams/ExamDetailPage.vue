<template>
  <v-container class="max-w-4xl mx-auto px-4 py-8" fluid>
    <v-btn variant="text" color="on-surface-variant" class="mb-6 px-0" to="/dashboard/exams" prepend-icon="mdi-arrow-left">
      Back to Exams
    </v-btn>

    <div v-if="examStore.loading" class="d-flex justify-center py-12">
      <v-progress-circular indeterminate color="primary" size="64"></v-progress-circular>
    </div>

    <div v-else-if="test" class="d-flex flex-column ga-6">
      <div class="d-flex flex-column flex-md-row align-md-start justify-space-between ga-4">
        <div>
          <div class="d-flex align-center ga-3 mb-2">
            <v-chip :color="statusColor" size="small" variant="flat" class="text-uppercase font-weight-bold letter-spacing-wide">
              {{ test.status }}
            </v-chip>
            <span class="text-caption text-on-surface-variant">{{ formatDate(test.created_at) }}</span>
          </div>
          <h1 class="text-h3 font-weight-bold text-on-surface mb-2">{{ test.title }}</h1>
          <p class="text-body-1 text-on-surface-variant">
            {{ test.question_count || (test.questions ? test.questions.length : 0) }} Questions
          </p>
        </div>
        
        <v-btn 
          v-if="test.status === 'completed'"
          color="primary" 
          size="large" 
          class="px-8 font-weight-bold"
          rounded="lg"
          elevation="2"
          :to="`/dashboard/results/${test.id}`"
        >
          View Results
        </v-btn>
        <v-btn 
          v-else
          color="primary-container" 
          class="text-on-primary-container px-8 font-weight-bold" 
          size="large" 
          rounded="lg"
          elevation="2"
          @click="startOrResumeExam"
          :loading="starting"
        >
          {{ test.status === 'in_progress' ? 'Resume Exam' : 'Start Exam' }}
        </v-btn>
      </div>

      <v-card class="bg-surface-container-lowest rounded-xl pa-6 mt-4 border" elevation="0">
        <h3 class="text-h6 font-weight-bold mb-4">Exam Overview</h3>
        <p class="text-body-2 text-on-surface-variant mb-4">
          This exam was generated by AI based on your selected document. Make sure you have a stable connection and enough time to complete it.
        </p>
        <v-list class="bg-transparent pa-0">
          <v-list-item class="px-0">
            <template v-slot:prepend>
              <v-icon icon="mdi-help-circle-outline" color="primary" class="mr-3"></v-icon>
            </template>
            <v-list-item-title class="font-weight-medium">Format</v-list-item-title>
            <v-list-item-subtitle>Multiple choice, true/false, and open questions</v-list-item-subtitle>
          </v-list-item>
          <v-list-item class="px-0">
            <template v-slot:prepend>
              <v-icon icon="mdi-timer-outline" color="primary" class="mr-3"></v-icon>
            </template>
            <v-list-item-title class="font-weight-medium">Time Limit</v-list-item-title>
            <v-list-item-subtitle>None (Take your time)</v-list-item-subtitle>
          </v-list-item>
          <v-list-item class="px-0">
            <template v-slot:prepend>
              <v-icon icon="mdi-check-decagram-outline" color="primary" class="mr-3"></v-icon>
            </template>
            <v-list-item-title class="font-weight-medium">Scoring</v-list-item-title>
            <v-list-item-subtitle>Results are calculated automatically upon submission</v-list-item-subtitle>
          </v-list-item>
        </v-list>
      </v-card>
    </div>

    <div v-else class="text-center py-12">
      <v-icon icon="mdi-alert-circle-outline" size="48" color="error" class="mb-4"></v-icon>
      <h2 class="text-h5 font-weight-bold text-on-surface mb-2">Exam Not Found</h2>
      <p class="text-body-1 text-on-surface-variant mb-6">The requested exam could not be loaded or doesn't exist.</p>
      <v-btn color="primary" to="/dashboard/exams">Return to Exams</v-btn>
    </div>
  </v-container>
</template>

<script setup lang="ts">
import { ref, computed, onMounted } from 'vue'
import { useRoute, useRouter } from 'vue-router'
import { useExamStore } from '@/store/examStore'

const route = useRoute()
const router = useRouter()
const examStore = useExamStore()

const examId = route.params.id as string
const starting = ref(false)

const test = computed(() => examStore.currentTest)

const statusColor = computed(() => {
  if (!test.value) return 'surface-variant'
  switch (test.value.status) {
    case 'completed': return 'success-container text-success'
    case 'in_progress': return 'primary-container text-primary-container-on'
    case 'ready': return 'secondary-container text-secondary-container-on'
    case 'generating': return 'warning-container text-warning'
    default: return 'surface-variant text-on-surface-variant'
  }
})

onMounted(async () => {
  if (examId) {
    await examStore.fetchTestDetail(examId)
  }
})

async function startOrResumeExam() {
  if (!test.value) return
  
  if (test.value.status !== 'in_progress') {
    starting.value = true
    try {
      await examStore.startTest(test.value.id)
    } catch (error) {
      console.error('Error starting test', error)
      starting.value = false
      return
    }
    starting.value = false
  }
  
  router.push(`/dashboard/exams/${test.value.id}/session`)
}

function formatDate(dateStr: string) {
  if (!dateStr) return ''
  const date = new Date(dateStr)
  return date.toLocaleDateString(undefined, { month: 'short', day: 'numeric', year: 'numeric' })
}
</script>

